#!/usr/bin/env python3
"""共用的身子（body.png）：水乡里的普通人——对襟短褂、腰带、裤子、布鞋。

没有自己身子图的角色（钓叟、船家少年、渔娘、货郎、小鼓手）都用这一张。原版是一块梯形加两条腿；
新图还是同样的位置和大小（原版 body.png 里图形的范围 x 66..170、y 56..209），只是画成人：
圆肩膀的短褂，下摆比裤子宽出一步，腰胯上一条腰带，下面是裆分开的两条裤腿和圆头的布鞋。

和头的配合（坐标都换到头的画布上）：
  上下对齐的时候，身子的画布比头的低 102 行，身子的顶在 y 158、脚底在 y 312。
  但游戏里的镜头是俯视的斜视角：头比身子离镜头近一点，在屏幕上头会往左上错开——第 1 关量到的是
  身子相对头往右下错开约 (21, 87) 个纹理像素、竖向压到 0.68；第 12 关约 (41, 89)、压到 0.54，
  而且错开多少还随主角在棋盘上的位置变。所以身子的顶不能画成一根露在外面的脖子：
  顶上窄（不到 30 像素宽）、两肩的坡陡，整块顶都藏得在头的下巴后面；头那边下巴伸到自己范围的底边
  （y 175 到 195），怎么错开都压在身子的上半天。

胸口不挖任何洞：主角站着不动的时候，拖尾的白色粒子是一团约 30×20 像素的点，在身子正中偏下
（x 100..129、y 109..128）的后面；守夜人的脚本里还量到过从胸口偏右 (x 134..162、y 69..89) 往下
到腰的一串 (x 115..149、y 91..138)。所以身子的上一大块（y 143 以上）全是实心的，腰带放在腰胯上（y 143..161）。
袖子只用轮廓表示（肩膀头 + 直筒的袖子），不和身子分开。

用法: python3 -I body.py <预览图的输出路径> [输出目录]
  不给输出目录就只出预览图。给了就在里面写出 body.png。
"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def _load(name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, name + ".py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


fig = _load("figure")
doodle = fig.doodle
REL = "assets/sprites/characters/body.png"
CX = 118.5          # 原版身子的中线（图形范围 x 66..170 的正中）




def jacket_and_legs():
    """整个身子的轮廓：领口 → 右肩 → 右袖 → 下摆角 → 收一步进裤子 → 右裤腿和布鞋 → 裆 → 左裤腿和布鞋 → 左边回到领口。
    左右故意不一样（原版的身子是马克笔随手画的，歪着、两条腿也不同）：右肩比左肩高，右边的下摆角比左边高，
    右腿略往外撇、脚略低，裆偏右，腰带左边低右边高。胸口（x 100..129、y 109..128 那一带，拖尾粒子在它后面）是实心的"""
    d = doodle.Mask(236, 248)
    d.shape([
        (119, 56),          # 领口的顶（藏在头后面）
        (129, 56.5),
        (133, 59),          # 右领口
        (141, 67),
        (149, 75.5),        # 右肩头：比左肩高
        (153.5, 88),
        (156.5, 104),
        (160, 122),
        (164.5, 140),
        (168.5, 154),
        (171.2, 163, 1),    # 右下摆角：比左边高
        (168.5, 171),
        (164, 175),
        (157, 177, 1),      # 下摆的底：往里收一步，接到裤子上
        (156.5, 185),
        (158.5, 194),
        (160.5, 201),       # 右腿略往外撇
        (160, 205.5),
        (156.5, 209),
        (148, 210.2),       # 右布鞋的底：比左脚略低
        (139, 209.6),
        (133.5, 207),
        (131.5, 200),
        (131, 193),
        (126.5, 188),       # 裆：偏右
        (122, 185),
        (117.5, 188),
        (112.5, 193),
        (112, 199),
        (110, 205),
        (106.5, 208),
        (98.5, 208.8),      # 左布鞋的底
        (90, 207.5),
        (86.5, 202),
        (85.5, 194),
        (86.5, 185),
        (83, 176.5, 1),     # 左下摆的底
        (76, 175.5),
        (70, 172),
        (67, 166, 1),       # 左下摆角：整张图最宽的地方
        (68.5, 156),
        (72.5, 142),
        (76.5, 124),
        (80.5, 106),
        (85, 90),
        (90, 80),           # 左肩头：比右肩低
        (97, 69),
        (105, 59.5),        # 左领口
        (110, 56.8),
    ])
    return d


def belt():
    """腰带：正中一条横的槽（两头是圆的），48 像素长、18 像素粗——游戏里镜头是俯视的，竖向会被压到一半多一点，
    太细的横线就没了。两头各留二十来像素不挖断，身子还是一整块（挖得太长，自检里的"细碎程度"就超了）"""
    d = doodle.Mask(236, 248)
    d.capsule((104.5, 154), (134, 150.5), 17)     # 略斜：左边低、右边高
    return d


def build():
    body = jacket_and_legs()
    body.soften(1.0)        # 肩头、下摆角这些接缝抹圆
    b = belt()
    b.soften(0.5)
    body.cut(b)
    return body.alpha()


if __name__ == "__main__":
    img = fig.to_canvas(build(), turn=False)     # 身子要立正（轮廓自己带着左右不一样），只抖线和变粗细
    ok = fig.verify(img, REL)
    if not fig.pure_white(img):
        print("  [不合格] 有不是纯白的不透明像素"); ok = False
    print("自检：%s" % ("合格" if ok else "不合格"))
    chars = os.path.abspath(os.path.join(HERE, "..", "..", "assets", "sprites", "characters"))
    out = fig.write(img, sys.argv[2] if len(sys.argv) > 2 else None, "body.png")
    if len(sys.argv) > 1:
        # 原版和新图都是"头 + 身子"上下叠着看的：原版那一行是原版的头配原版的身子；
        # 新图那一行先借定稿的守夜人的头（守夜人自己有蓑衣，这里只是借来看上下怎么接）
        fig.preview(sys.argv[1], "共用身子 body.png（借守夜人的头看接缝）",
                    os.path.join(chars, "default.png"), out, "assets/sprites/characters/default.png", REL)
